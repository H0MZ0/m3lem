"""Render the HCP snapshot migration from the two workbooks (see docs/catalog.md).

python3 scripts/catalog/cities.py population.xlsx urban-housing.xlsx > migration.sql
"""
import collections
import hashlib
import re
import sys
import unicodedata
import zipfile
import xml.etree.ElementTree as ET


def rows(path, digest):
    with open(path, "rb") as source:
        assert hashlib.file_digest(source, "sha256").hexdigest() == digest
    with zipfile.ZipFile(path) as book:
        strings = ["".join(x.itertext()) for x in ET.fromstring(book.read("xl/sharedStrings.xml"))]
        for row in ET.fromstring(book.read("xl/worksheets/sheet1.xml")).findall(".//{*}row"):
            yield {c.get("r").rstrip("0123456789"): strings[int(v.text)] if c.get("t") == "s" else v.text
                   for c in row if (v := c.find("{*}v")) is not None}


def slug(text):
    latin = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().lower()
    return re.sub("[^a-z0-9]+", "-", latin).strip("-")


def quote(value):
    return "'" + value.replace("'", "''") + "'"


housing = rows(sys.argv[2], "c5ca0d86eef04cac4692cc0fff691e81f77e73726515b12eb17a0d7f3a8ff421")
urban, parents = set(), set()
for row in housing:
    name = row.get("B", "")
    if name.startswith("Commune "):
        parent = row["A"]
        if row.get("C", "").isdigit() and int(row["C"]) > 0:
            urban.add(parent)
    elif name.startswith("dont "):
        parents.add(parent)
# Do not count the rural parent commune again under another name.
urban -= parents
urban.add("120660103")  # Lagouira: municipality footnoted in the population workbook.
assert len(urban) == 221

places = []
regions = {}
for row in rows(sys.argv[1], "7e9d3d402cc2fd0d9c4fc941c4f23c6a5e5ddcbefbba80b7540267f8e2728dca"):
    fr = row.get("A", "").strip()
    ar = row.get("F", "").strip()
    if fr.startswith("Région ") and "(milieu" not in fr:
        region = f"region-{int(row['G']):02}"
        regions[region] = (ar.removeprefix("جهة "), re.sub(r"^Région (de |d')", "", fr))
    if fr.startswith(("Province ", "Préfecture ")) and not fr.startswith("Préfecture d'arrondissements"):
        province = re.sub(r"^(Province|Préfecture) (de |d')", "", fr)
        province_ar = re.sub(r"^(عمالة|إقليم) ", "", ar)
    if fr.startswith("dont ") or (fr.startswith("Commune ") and row["G"] in urban):
        fr = re.sub(r"^(Commune |dont le centre urbain )(de |d')", "", fr).strip(" *")
        ar = re.sub(r"^(جماعة |تضم المركز الحضري )", "", ar).strip(" *")
        places.append((fr, ar, province, province_ar, region))
assert len(places) == 385
counts = collections.Counter(slug(fr) for fr, *_ in places)
aliases = {"casablanca": "Casa|كازا|الدار البيضا", "marrakech": "Marrakesh|مراكش",
           "tanger": "Tangier|Tanja", "fes": "Fez", "kenitra": "القنيطرة|قنيطرة",
           "assilah": "Asilah", "taroudannt": "Taroudant", "es-semara": "Smara",
           "laayoune": "Laayoun", "el-jadida": "الجديدة|Mazagan"}
records = []
members = collections.defaultdict(list)
for fr, ar, province, province_ar, region in places:
    key = slug(fr)
    if counts[key] > 1:
        key += "-" + slug(province)
        fr, ar = f"{fr} ({province})", f"{ar} ({province_ar})"
    records.append((key, ar, fr, aliases.get(key, "")))
    members[region].append(key)
assert len(set(r[0] for r in records)) == len(records)
if "--regions" in sys.argv[3:]:
    assert len(members) == len(regions) == 12
    print("""-- HCP RGPH 2024; generated by scripts/catalog/cities.py --regions.
begin;
alter table directory.catalog drop constraint catalog_kind_check, drop constraint catalog_check;
alter table directory.catalog add check (kind in ('region','city','trade','area')),
  add check (case when kind in ('trade','region') then parent is null
                  when kind='area' then parent is not null else true end);
insert into directory.catalog(slug, kind, ar, fr) values""")
    print(",\n".join("  (" + ",".join(map(quote, (key, "region", *regions[key]))) + ")" for key in sorted(regions)) + ";")
    for key, cities in sorted(members.items()):
        print(f"update directory.catalog set parent={quote(key)} where kind='city' and slug in (")
        print(",\n".join("  "+",".join(map(quote,sorted(cities)[i:i+6])) for i in range(0,len(cities),6)) + ");")
    print("commit;")
    sys.exit()
print("-- HCP, RGPH 2024: urban municipalities and urban centres. CC BY 4.0.")
print("-- Generated by scripts/catalog/cities.py; sources and adaptations: docs/catalog.md.")
print("begin;\ninsert into directory.catalog(slug,kind,ar,fr,aliases)")
print("select slug,'city',ar,fr,string_to_array(aka,'|') from (values")
print(",\n".join("  (" + ",".join(map(quote, r)) + ")" for r in sorted(records)))
print(") v(slug,ar,fr,aka) on conflict(slug) do nothing;")
print("""insert into directory.catalog(slug,kind,parent,ar,fr) values
  ('maarif','area','casablanca','المعاريف','Maârif'),
  ('bourgogne','area','casablanca','بوركون','Bourgogne'),
  ('sidi-maarouf','area','casablanca','سيدي معروف','Sidi Maârouf')
on conflict(slug) do nothing;
commit;""")
